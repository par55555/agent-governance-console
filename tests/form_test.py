import asyncio, json, os, sys
from pathlib import Path
from playwright.async_api import async_playwright
HERE = Path(__file__).resolve().parent
OUT = HERE / 'out'; OUT.mkdir(exist_ok=True)
BASE = os.environ.get('AGC_BASE', 'http://127.0.0.1:8765/index.html')
CHROME = os.environ.get('CHROME_PATH')  # optional: path to a Chrome binary; Playwright's bundled Chromium is used otherwise
MOCK = (HERE / 'mockdb.js').read_text()
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(**({'executable_path': CHROME} if CHROME else {}))
        errs=[]
        ctx = await b.new_context(viewport={'width':1440,'height':940})
        await ctx.add_init_script(MOCK)
        pg = await ctx.new_page()
        pg.on('pageerror', lambda e: errs.append('pageerror: '+str(e)))
        pg.on('console', lambda m: errs.append('console.'+m.type+': '+m.text) if m.type=='error' and 'fonts' not in m.text and 'ERR_TUNNEL' not in m.text else None)
        await pg.goto(BASE+'#o2c'); await pg.wait_for_timeout(800)
        print('pill:', await pg.inner_text('#src'))
        await pg.screenshot(path=str(OUT / 'live_o2c.png'))
        await pg.click('.sec-h [data-add]'); await pg.wait_for_timeout(300)
        await pg.screenshot(path=str(OUT / 'form_blank.png'))
        await pg.click('[data-fx="save"]'); await pg.wait_for_timeout(300)
        print('errors after empty save:', await pg.evaluate('Object.keys(window.__AGC.FORM.errors)'))
        await pg.screenshot(path=str(OUT / 'form_errors.png'))
        # fill
        await pg.fill('#f-name', 'Dispute Intake Agent')
        await pg.fill('#f-owner_name', 'Tanya Holloway'); await pg.fill('#f-owner_title', 'Manager, Deductions & Disputes')
        await pg.select_option('#f-home_subprocess', 'Deductions & disputes')
        await pg.select_option('#f-autonomy', '2')
        await pg.fill('#f-summary', 'Turns retailer dispute emails into structured dispute cases with the invoice, deduction code and evidence attached.')
        await pg.fill('#f-trigger', 'Event: new email in the disputes@ mailbox')
        await pg.fill('#f-instructions', 'You are the Dispute Intake Agent for Meridian Consumer Brands. For each dispute email, find the invoice and deduction, attach proof of delivery, and open a dispute case. Never accept or reject a dispute yourself.')
        await pg.fill('[data-r="inputs"][data-i="0"][data-k="system"]', 'Gmail · disputes@ mailbox'); await pg.fill('[data-r="inputs"][data-i="0"][data-k="what"]', 'Retailer dispute emails')
        await pg.click('#sec-inputs [data-fx="add"]')
        await pg.fill('[data-r="inputs"][data-i="1"][data-k="system"]', 'project44 · Proof of delivery'); await pg.select_option('[data-r="inputs"][data-i="1"][data-k="process"]', 'i2d')
        await pg.fill('[data-r="tools"][data-i="0"][data-k="name"]', 'open_dispute_case'); await pg.fill('[data-r="tools"][data-i="0"][data-k="system"]', 'Salesforce Service Cloud')
        await pg.select_option('[data-r="tools"][data-i="0"][data-k="process"]', 'i2r'); await pg.select_option('[data-r="tools"][data-i="0"][data-k="access"]', 'write')
        await pg.fill('[data-r="tools"][data-i="0"][data-k="approval_by"]', 'Dispute specialist')
        await pg.fill('[data-r="outputs"][data-i="0"][data-k="destination"]', 'Salesforce Service Cloud · Dispute cases'); await pg.select_option('[data-r="outputs"][data-i="0"][data-k="process"]', 'i2r')
        await pg.fill('[data-r="users"][data-i="0"][data-k="role"]', 'Deduction analysts'); await pg.fill('[data-r="users"][data-i="0"][data-k="people"]', '14')
        await pg.click('#sec-users [data-fx="add"]')
        await pg.select_option('[data-r="users"][data-i="1"][data-k="process"]', 'i2r'); await pg.fill('[data-r="users"][data-i="1"][data-k="role"]', 'Dispute resolution specialists'); await pg.fill('[data-r="users"][data-i="1"][data-k="people"]', '6')
        await pg.fill('[data-l="guardrails"][data-i="0"]', 'Never accepts or rejects a dispute; cases only.')
        await pg.click('[data-fx="md"]'); await pg.wait_for_timeout(200)
        await pg.screenshot(path=str(OUT / 'form_filled.png'))
        print('id:', await pg.input_value('#f-agent_id'), '| errors left before save:', await pg.evaluate('Object.keys(window.__AGC.FORM.errors)'), '| foot:', await pg.inner_text('.f-msg'))
        await pg.click('[data-fx="save"]'); await pg.wait_for_timeout(700)
        print('writes:', await pg.evaluate('window.__writes'), 'hash:', await pg.evaluate('location.hash'))
        await pg.screenshot(path=str(OUT / 'after_add.png'))
        doc = await pg.evaluate("JSON.stringify(window.__store.get('agents/o2c-dispute-intake'))")
        print('stored doc:', doc[:600])
        # edit flow
        await pg.click('[data-edit]'); await pg.wait_for_timeout(300)
        await pg.fill('#f-version', '0.2.0'); await pg.select_option('#f-lifecycle', 'production'); await pg.wait_for_timeout(100)
        await pg.click('[data-fx="save"]'); await pg.wait_for_timeout(600)
        d2 = json.loads(await pg.evaluate("JSON.stringify(window.__store.get('agents/o2c-dispute-intake'))"))
        print('after edit:', d2['version'], d2['lifecycle'], d2['deployed_at'], d2['created_by'], d2['source'])
        await pg.click('[data-tab="usage"]'); await pg.wait_for_timeout(200)
        await pg.screenshot(path=str(OUT / 'after_edit_usage.png'))
        # refused save
        await pg.click('[data-edit]'); await pg.wait_for_timeout(200)
        await pg.fill('#f-version', '0.3.0'); await pg.evaluate("window.__failNext='invalid_argument'")
        await pg.click('[data-fx="save"]'); await pg.wait_for_timeout(300)
        print('refused msg:', await pg.inner_text('.f-msg'))
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(150)
        print('confirm shown:', await pg.is_visible('[data-fx="discard"]'))
        await pg.click('[data-fx="discard"]'); await pg.wait_for_timeout(150)
        print('add buttons disabled after refusal:', await pg.evaluate("[...document.querySelectorAll('[data-add]')].every(b=>b.disabled)"))
        await pg.goto(BASE+'#o2c'); await pg.wait_for_timeout(600)
        # snapshot (no runtime)
        ctx2 = await b.new_context(viewport={'width':1440,'height':900}); pg2 = await ctx2.new_page()
        pg2.on('pageerror', lambda e: errs.append('snap pageerror: '+str(e)))
        await pg2.goto(BASE+'#r2r'); await pg2.wait_for_timeout(800)
        print('snapshot pill:', await pg2.inner_text('#src'), '| add disabled:', await pg2.evaluate("document.querySelector('.add-btn').disabled"), '| agents:', await pg2.evaluate('window.__AGC.AGENTS.length'))
        await pg2.screenshot(path=str(OUT / 'snapshot_r2r.png'))
        print('\n'.join(errs) or 'no page errors')
        await b.close()
asyncio.run(main())
